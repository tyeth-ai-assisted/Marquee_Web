#!/usr/bin/env node
/**
 * Regenerate public/js/canvas/pixelfont-data.js from the Adafruit GFX Library.
 *
 *   node scripts/gen-pixelfonts.mjs path/to/Adafruit-GFX-Library
 *
 * Reads two fonts and keeps printable ASCII (0x20–0x7E) of each:
 *   glcdfont.c          the classic 5×7 font: 5 column bytes per character, LSB at the top
 *   Fonts/TomThumb.h    Tom Thumb 3×5, a GFXfont: a packed bitmap plus per-glyph metrics
 *
 * Both are written in one shape, so the renderer has a single path: per character
 * [advance, xOffset, top, width, ...rows], where `top` is the first row of the glyph in a
 * line cell `lineH` pixels tall and each row is a bitmask of `width` bits, leftmost pixel
 * in the highest bit.
 */
import fs from 'node:fs';
import path from 'node:path';

const lib = process.argv[2];
if (!lib) { console.error('usage: gen-pixelfonts.mjs <Adafruit-GFX-Library dir>'); process.exit(1); }

const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
const nums = (s) => [...s.matchAll(/-?0x[0-9A-Fa-f]+|-?\b\d+\b/g)].map((m) => Number(m[0]));
const FIRST = 0x20, LAST = 0x7E;

function glcd() {
  const src = stripComments(fs.readFileSync(path.join(lib, 'glcdfont.c'), 'utf8'));
  const bytes = nums(src.match(/font\[\]\s*PROGMEM\s*=\s*\{([\s\S]*?)\};/)[1]);
  const glyphs = [];
  for (let c = FIRST; c <= LAST; c++) {
    const cols = bytes.slice(c * 5, c * 5 + 5);
    const rows = [];
    for (let y = 0; y < 8; y++) {
      let row = 0;
      for (let x = 0; x < 5; x++) row = (row << 1) | ((cols[x] >> y) & 1);
      rows.push(row);
    }
    glyphs.push([6, 0, 0, 5, ...rows]);
  }
  return { name: 'Adafruit GFX 5×7', lineH: 8, ascent: 7, advance: 6, glyphs };
}

function tomThumb() {
  // Only the glyph table up to the extended-character #if is wanted.
  const raw = fs.readFileSync(path.join(lib, 'Fonts', 'TomThumb.h'), 'utf8');
  const src = stripComments(raw.replace(/#if\s*\(?\s*TOMTHUMB_USE_EXTENDED[\s\S]*?#endif/g, ''));
  const bitmap = nums(src.match(/Bitmaps\[\]\s*PROGMEM\s*=\s*\{([\s\S]*?)\};/)[1]);
  const table = [...src.match(/Glyphs\[\]\s*PROGMEM\s*=\s*\{([\s\S]*?)\};/)[1].matchAll(/\{([^}]*)\}/g)].map((m) => nums(m[1]));
  const yAdvance = 6, ascent = 5;
  const glyphs = [];
  for (let c = FIRST; c <= LAST; c++) {
    const [off, w, h, adv, xo, yo] = table[c - FIRST];
    const rows = [];
    let bit = 0;
    for (let y = 0; y < h; y++) {
      let row = 0;
      for (let x = 0; x < w; x++, bit++) row = (row << 1) | ((bitmap[off + (bit >> 3)] >> (7 - (bit & 7))) & 1);
      rows.push(row);
    }
    glyphs.push([adv, xo, ascent + yo, w, ...rows]);
  }
  return { name: 'Tom Thumb 3×5', lineH: yAdvance, ascent, advance: 4, glyphs };
}

